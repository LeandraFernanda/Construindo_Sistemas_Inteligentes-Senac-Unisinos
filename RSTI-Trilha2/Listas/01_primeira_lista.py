print("Quantidade de elementos:", len(objetos))
print("Primeiro objeto:", objetos[0])
print("Último objeto:", objetos[-1])
# Substituindo o terceiro objeto
objetos[2] = "Cadeira Gamer"
print("Lista atualizada:", objetos)
